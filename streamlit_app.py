# --------------------------------------------------------------------------- #
@st.cache_resource(show_spinner=False)
def get_analyst() -> Analyst:
    return Analyst()


@st.cache_data(show_spinner=False)
def kpis(_analyst: Analyst) -> dict:
    db = _analyst.db
    monthly = db.run(
        "SELECT substr(order_date,1,7) AS m, ROUND(SUM(revenue),2) AS revenue, "
        "ROUND(SUM(profit),2) AS profit, COUNT(DISTINCT order_id) AS orders "
        "FROM v_sales GROUP BY 1 ORDER BY 1"
    ).dataframe
    last, prev = monthly.iloc[-1], monthly.iloc[-2]
    return {
        "monthly": monthly,
        "month": last["m"],
        "revenue": last["revenue"],
        "revenue_delta": (last["revenue"] - prev["revenue"]) / prev["revenue"] * 100,
        "orders": int(last["orders"]),
        "orders_delta": (last["orders"] - prev["orders"]) / prev["orders"] * 100,
        "margin": last["profit"] / last["revenue"] * 100,
        "aov": last["revenue"] / last["orders"],
    }


def kpi_card(label: str, value: str, delta: float | None = None) -> str:
    d = ""
    if delta is not None:
        cls = "delta-up" if delta >= 0 else "delta-down"
        d = f"<div class='{cls}'>{delta:+.1f}% vs prior month</div>"
    return (f"<div class='kpi'><div class='label'>{label}</div>"
            f"<div class='value'>{value}</div>{d}</div>")


def render_chart(spec) -> None:
    if spec.kind == "table" or spec.data.empty:
        if not spec.data.empty:
            st.dataframe(spec.data, use_container_width=True, hide_index=True)
        return
    if spec.kind == "metric":
        st.metric(spec.title or spec.y, f"{spec.data[spec.y].iloc[0]:,.2f}")
        return
    fig = charts.to_plotly(spec)
    if fig is not None:
        st.plotly_chart(fig, use_container_width=True)


def render_answer(ans) -> None:
    st.markdown(ans.insight)

    if ans.chart.data is not None and not ans.chart.data.empty:
        render_chart(ans.chart)

    for extra in ans.extra_charts:
        with st.expander(extra.title or "More detail", expanded=False):
            render_chart(extra)

    tabs = st.tabs(["Data", "SQL", "How I got here"])
    with tabs[0]:
        if ans.data.empty:
            st.caption("No rows.")
        else:
            st.dataframe(ans.data, use_container_width=True, hide_index=True)
            st.download_button(
                "Download CSV", ans.data.to_csv(index=False).encode(),
                file_name="analysis.csv", mime="text/csv",
                key=f"dl-{abs(hash(ans.question))}-{len(ans.data)}",
            )
    with tabs[1]:
        st.code(ans.sql, language="sql")
        st.caption(f"Generated by: **{ans.sql_source}**")
    with tabs[2]:
        st.markdown(
            f"<span class='pill'>{ans.plan.intent}</span>"
            f"<span class='pill'>{ans.plan.metric}</span>"
            f"<span class='pill'>{ans.elapsed_s:.2f}s</span>",
            unsafe_allow_html=True)
        for step in ans.trace:
            st.text(f"• {step}")
        if ans.facts:
            st.caption("Facts passed to the writer:")
            st.text(ans.facts)


