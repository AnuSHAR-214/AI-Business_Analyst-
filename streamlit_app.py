try:
    analyst = get_analyst()
except FileNotFoundError as exc:
    st.error(str(exc))
    st.info("Run `python data/generate_data.py` first, then reload this page.")
    st.stop()

with st.sidebar:
    st.header("AI Business Analyst")
    st.caption("Ask a business question in plain English. The assistant writes "
               "the SQL, runs it, analyses the result and explains it.")
    st.divider()
    st.markdown(f"**LLM:** `{analyst.llm.provider}` · `{analyst.llm.model}`")
    if analyst.llm.is_offline:
        st.info("Running in offline mode — SQL and insights come from the "
                "built-in rule engine. Set `ANTHROPIC_API_KEY` or "
                "`OPENAI_API_KEY` in `.env` for LLM-written answers.")
        with st.expander("Why offline?"):
            for reason in analyst.llm.reasons:
                st.text(f"• {reason}")
            st.caption("Run `python check_llm.py` for a full diagnosis.")
    st.markdown(f"**Data:** {analyst.data_start} → {analyst.data_end}")
    st.divider()
    st.markdown("**Try asking**")
    for q in EXAMPLE_QUESTIONS:
        if st.button(q, use_container_width=True, key=f"ex-{q}"):
            st.session_state.pending = q
    st.divider()
    if st.button("Clear conversation", use_container_width=True):
        st.session_state.history = []
        st.rerun()

left, right = st.columns([2.1, 1], gap="large")

with right:
    k = kpis(analyst)
    st.markdown(f"#### Snapshot · {k['month']}")
    st.markdown(kpi_card("Revenue", f"{k['revenue']:,.0f}", k["revenue_delta"]),
                unsafe_allow_html=True)
    st.markdown(kpi_card("Orders", f"{k['orders']:,}", k["orders_delta"]),
                unsafe_allow_html=True)
    st.markdown(kpi_card("Gross margin", f"{k['margin']:.1f}%"),
                unsafe_allow_html=True)
    st.markdown(kpi_card("Avg order value", f"{k['aov']:,.0f}"),
                unsafe_allow_html=True)
    spark = charts.ChartSpec(kind="line", title="Revenue by month",
                             x="m", y="revenue", data=k["monthly"])
    render_chart(spark)

with left:
    st.session_state.setdefault("history", [])
    st.session_state.setdefault("pending", None)

    for item in st.session_state.history:
        with st.chat_message("user"):
            st.write(item["question"])
        with st.chat_message("assistant"):
            render_answer(item["answer"])

    typed = st.chat_input("e.g. Why did revenue drop in March?")
    question = typed or st.session_state.pending
    st.session_state.pending = None

    if question:
        with st.chat_message("user"):
            st.write(question)
        with st.chat_message("assistant"):
            with st.spinner("Thinking, querying, analysing…"):
                ans = analyst.ask(question)
            render_answer(ans)
        st.session_state.history.append({"question": question, "answer": ans})
